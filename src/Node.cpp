/*******************************************************************************
 * @brief Construct a new Node:: Node object
 * 
*******************************************************************************/
Node::Node() : _accuracy(-1) {}



/*******************************************************************************
 * @brief Construct a new Node:: Node object
 * 
 * @param s 
*******************************************************************************/
Node::Node(std::set<int> s) : _featureSet(s),
                              _accuracy(-1) {}



/*******************************************************************************
 * @brief Construct a new Node:: Node object
 * 
 * @param node 
*******************************************************************************/
Node::Node(const Node& node) : _featureSet(node._featureSet), 
                               _accuracy(node._accuracy) {}



/*******************************************************************************
 * @brief Destroy the Node:: Node object
 * 
*******************************************************************************/
Node::~Node() {}



